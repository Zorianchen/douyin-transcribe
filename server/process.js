async function processText(action, data, ai = null) {
  const cfg = ACTIONS[action];
  if (!cfg) {
    const err = new Error('不支持的加工类型：' + action);
    err.statusCode = 400;
    throw err;
  }
  const text = buildText(data);
  if (!text || text.length < 10) {
    const err = new Error('文字稿内容太短，无法加工');
    err.statusCode = 400;
    throw err;
  }
  // 超长则截断（保护上下文，约 8000 字）
  const clipped = text.length > 8000 ? text.slice(0, 8000) + '\n（内容较长，以下省略）' : text;
  const result = await chat(cfg.system, clipped, { temperature: 0.6, timeout: 90000 }, ai);
  return { action, label: cfg.label, result: String(result || '').trim() };
}

module.exports = { processText, ACTIONS };
